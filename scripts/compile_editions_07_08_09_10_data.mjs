function writeEditionData(editionId, posts) {
  const campPath = path.join(ROOT, 'campaign', 'editions', editionId, 'edition_data.json');
  const pubPath = path.join(ROOT, 'public', 'campaign', 'editions', editionId, 'edition_data.json');
  fs.mkdirSync(path.dirname(campPath), { recursive: true });
  fs.mkdirSync(path.dirname(pubPath), { recursive: true });
  
  const content = JSON.stringify(posts, null, 2);
  fs.writeFileSync(campPath, content, 'utf8');
  fs.writeFileSync(pubPath, content, 'utf8');
  console.log(`✓ Wrote edition_data.json for ${editionId}`);
}

